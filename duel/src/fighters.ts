/** 任意挑选两个英雄自由组合生成真实物理对局（顶部血条与半场边框统一采用左红右蓝，球体保留英雄自身代表色） */
export function buildCustomMatchup(heroA: FighterConfig, heroB: FighterConfig): DuelMatchupPreset {
  const isSkillBall = heroA.combatMode === "skillball" || heroB.combatMode === "skillball";
  const aKey = heroA.ballSkillKind ? heroA.ballSkillKind.split("_")[0] : heroA.name;
  const bKey = heroB.ballSkillKind ? heroB.ballSkillKind.split("_")[0] : heroB.name;
  return {
    id: `${aKey}_vs_${bKey}`,
    title: `${heroA.name} VS ${heroB.name}`,
    fighterA: { ...heroA, id: "A" },
    fighterB: { ...heroB, id: "B" },
    hook: `${heroA.title} VS ${heroB.title}，谁能活到最后？`,
    mode: isSkillBall ? "skillball" : "weapon",
  };
}
